function pdfText(buf: Buffer): string {
  return buf.toString("latin1");
}

function pageCount(buf: Buffer): number {
  const m = /\/Type \/Pages \/Kids \[[^\]]*\] \/Count (\d+)/.exec(pdfText(buf));
  assert.ok(m);
  return Number(m[1]);
}

function assertValidXref(buf: Buffer): void {
  const s = pdfText(buf);
  const xrefAt = Number(/startxref\s+(\d+)\s+%%EOF\s*$/.exec(s)?.[1]);
  const head = /^xref\n0 (\d+)\n/.exec(s.slice(xrefAt));
  assert.ok(head);
  for (let n = 1; n < Number(head[1]); n++) {
    const pos: number = xrefAt + head[0].length + n * 20;
    const off: number = Number(s.slice(pos, pos + 10));
    assert.equal(s.slice(off, off + `${n} 0 obj`.length), `${n} 0 obj`);
  }
}

describe("formatting helpers", () => {
  it("formats Indian grouping", () => {
    assert.equal(formatIndianNumber(123456.5), "1,23,456.50");
    assert.equal(formatIndianNumber(1234567890), "1,23,45,67,890.00");
    assert.equal(formatIndianNumber(999), "999.00");
    assert.equal(formatIndianNumber(1000, 0), "1,000");
    assert.equal(formatIndianNumber(-12345.678), "-12,345.68");
    assert.equal(formatInr(0), "Rs. 0.00");
  });

  it("formats dates in UTC as DD Mon YYYY", () => {
    assert.equal(formatPoDate("2026-10-13T23:59:59.000Z"), "13 Oct 2026");
    assert.equal(formatPoDate("2026-01-05"), "05 Jan 2026");
    assert.equal(formatPoDate(null), "");
    assert.equal(formatPoDate("not a date"), "not a date");
  });
});

describe("renderPurchaseOrderPdf", () => {
  it("renders a 2-line PO with header, parties, lines and totals", () => {
    const doc = fixture([line(1), line(2, { rate: null })]);
    const buf = renderPurchaseOrderPdf(doc);
    const s = pdfText(buf);
    assert.ok(s.startsWith("%PDF-1.4"));
    assert.ok(s.trimEnd().endsWith("%%EOF"));
    assertValidXref(buf);
    assert.equal(pageCount(buf), 1);
    for (const needle of [
      "(PURCHASE ORDER)",
      "(PO-2026-000042)",
      "(Acme Optics Supplies)",
      "(GSTIN: 27BBBBB1111B1Z9)",
      "(GSTIN: 07AAAAA0000A1Z5)",
      "(PAN: BBBBB1111B)",
      "(Attn: R. Sharma)",
      "(SPH -2.25 / CYL -0.75)",
      "(+4.25)",
      "(13 Oct 2026)",
      "(14 Oct 2026)",
      "(20 Oct 2026)",
      "(Warehouse: WH-DEL-01)",
      "(Rate not specified for some lines - amounts exclude unpriced lines.)",
      "(Page 1 of 1)",
      "(Generated by DrishX \\267 PO-2026-000042)",
      "(Rs. 1,380.50)", // 125.5 * 11
      "(PO Qty)",
    ]) {
      assert.ok(s.includes(needle), `missing ${needle}`);
    }
    // Notes: parentheses escaped and em dash normalised.
    assert.ok(s.includes("\\(store\\) before dispatch - thanks!"));
    // No "Sent" row when sentAt is null; no internal ids.
    assert.ok(!s.includes("(Sent)"));
  });

  it("omits the unpriced note when every line has a rate", () => {
    const s = pdfText(renderPurchaseOrderPdf(fixture([line(1), line(2)], { notes: null })));
    assert.ok(!s.includes("Rate not specified"));
    assert.ok(!s.includes("(Notes)"));
  });

  it("paginates 120 lines and repeats the table header", () => {
    const lines = Array.from({ length: 120 }, (_, i) => line(i + 1));
    const buf = renderPurchaseOrderPdf(fixture(lines));
    const s = pdfText(buf);
    assertValidXref(buf);
    const pages = pageCount(buf);
    assert.ok(pages >= 3, `expected >= 3 pages, got ${pages}`);
    assert.equal(s.split("(PO Qty) Tj").length - 1, pages);
    assert.equal(s.split("(Purchase Order PO-2026-000042 \\(continued\\)) Tj").length - 1, pages - 1);
    for (let i = 1; i <= pages; i++) assert.ok(s.includes(`(Page ${i} of ${pages})`));
    assert.ok(s.includes("(120) Tj"));
  });

  it("handles long labels, empty optional fields and no lines", () => {
    const doc = fixture(
      [
        line(1, {
          productLabel: "An extremely long product label ".repeat(6),
          powerLabel: null,
          rangeLabel: null,
        }),
      ],
      {
        supplier: { name: "Bare Supplier", addressLines: [] },
        expectedDelivery: null,
        approvedAt: null,
      }
    );
    const s = pdfText(renderPurchaseOrderPdf(doc));
    assert.ok(s.includes("(Bare Supplier)"));
    assert.ok(s.includes("(Not specified)"));
    assert.ok(!s.includes("(Approved)"));
    assert.ok(/\.\.\.\) Tj/.test(s), "long product label truncated");

    const empty = pdfText(renderPurchaseOrderPdf(fixture([])));
    assert.ok(empty.includes("(No lines on this purchase order.)"));
  });
});
