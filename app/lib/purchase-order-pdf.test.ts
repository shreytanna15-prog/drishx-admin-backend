function line(n: number, over: Partial<PurchaseOrderDocumentLine> = {}): PurchaseOrderDocumentLine {
  const rate = over.rate === undefined ? 125.5 : over.rate;
  const poQuantity = over.poQuantity ?? 10 + n;
  return {
    lineNumber: n,
    lensType: "SINGLE_VISION",
    productLabel: `SV Blue Cut 1.56 Product ${n}`,
    rangeLabel: "Stock 1.56",
    powerLabel: n % 2 ? "SPH -2.25 / CYL -0.75" : "+4.25",
    requiredQuantity: poQuantity,
    poQuantity,
    receivedQuantity: 0,
    cancelledQuantity: 0,
    outstandingQuantity: poQuantity,
    rate,
    amount: rate == null ? 0 : rate * poQuantity,
    ...over,
  };
}

